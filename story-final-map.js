"use strict";

/*
==========================================================
 杭州探索録
 FINAL MAP Ver.1.0

 雷峰塔・塔内

 ・第八章専用
 ・通常探索では入れない
 ・戦闘なし
 ・静かに上へ登るための専用マップ
==========================================================
*/

(function(){

  // ========================================================
  // TILE TYPE
  // 既存マップの歩行可能タイルを流用
  // ========================================================

  const baseGrid =
    MAPS.lake.grid;

  if(!baseGrid){
    return;
  }


  // 既存の西湖マップから
  // 「歩けるタイル」を取得する
  const WALK_TILE =
    baseGrid[
      MAPS.lake.spawn.y
    ][
      MAPS.lake.spawn.x
    ];


  // ========================================================
  // MAP SIZE
  // ========================================================

  const W = 34;
  const H = 42;


  // ========================================================
  // GRID
  // ========================================================

  const grid = [];

  for(let y=0; y<H; y++){

    const row = [];

    for(let x=0; x<W; x++){

      /*
        基本的には壁扱いにしたいので、
        西湖マップ左上付近のタイルを背景用に借りる。
      */

      row.push(
        baseGrid[0][0]
      );

    }

    grid.push(row);

  }


  // ========================================================
  // WALKABLE PATH
  // ========================================================

  function fillWalkable(
    x1,
    y1,
    x2,
    y2
  ){

    for(
      let y=y1;
      y<=y2;
      y++
    ){

      for(
        let x=x1;
        x<=x2;
        x++
      ){

        if(
          grid[y] &&
          grid[y][x] !== undefined
        ){

          grid[y][x] =
            WALK_TILE;

        }

      }

    }

  }


  /*
    雷峰塔内部。

    一本道ではあるが、
    少し蛇行させることで
    「上っている」感覚を出す。
  */


  // 入口
  fillWalkable(
    14,36,
    19,40
  );


  // 第一階段
  fillWalkable(
    14,29,
    19,36
  );


  // 第一踊り場
  fillWalkable(
    8,27,
    19,31
  );


  // 第二階段
  fillWalkable(
    8,20,
    13,28
  );


  // 第二踊り場
  fillWalkable(
    8,18,
    25,22
  );


  // 第三階段
  fillWalkable(
    20,11,
    25,20
  );


  // 上層
  fillWalkable(
    10,8,
    25,13
  );


  // 最奥
  fillWalkable(
    14,3,
    20,10
  );


  // ========================================================
  // MAP
  // ========================================================

  MAPS.leifengTower = {

    name:
      "雷峰塔・塔内",

    subtitle:
      "雷峰塔 · 西湖 · 白蛇伝",

    ambient:
      "night",

    grid:grid,


    spawn:{

      x:16,
      y:38

    },


    buildings:[],

    stalls:[],

    lanternRows:[],

    props:[],

    interactables:[],

    exits:[]

  };


  console.log(
    "杭州探索録 Final Map / 雷峰塔 loaded"
  );

})();
